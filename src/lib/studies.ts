/** Nummer einer Quelle (ab 1), wie sie im Text steht. */
export function sourceNumber(id: string): number {
  return SOURCES.findIndex((s) => s.id === id) + 1;
}

/** `[1, 3]` aus IDs, unbekannte fallen weg. */
export function citation(ids: string[]): string {
  const numbers = ids.map(sourceNumber).filter((n) => n > 0).sort((a, b) => a - b);
  return numbers.length ? `[${numbers.join(', ')}]` : '';
}
